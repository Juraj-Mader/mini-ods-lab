-- =====================================================================
-- SRC_APP: simulated source application (a small order system).
-- In a real company this would be core banking, cards, CRM, ...
-- The ODS never writes here - it only reads (SELECT grant at the end).
-- =====================================================================
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE src_app.customers (
    customer_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    VARCHAR2(100) NOT NULL,
    email        VARCHAR2(200) NOT NULL,
    country      VARCHAR2(2)   DEFAULT 'SK' NOT NULL,
    created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE src_app.orders (
    order_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  NUMBER        NOT NULL REFERENCES src_app.customers (customer_id),
    order_date   DATE          NOT NULL,
    amount       NUMBER(12,2)  NOT NULL,
    currency     VARCHAR2(3)   DEFAULT 'EUR' NOT NULL,
    status       VARCHAR2(20)  NOT NULL,
    updated_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT orders_status_chk
        CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED'))
);

-- The extract job will ask "what changed since my last run?" -> index on updated_at
CREATE INDEX src_app.orders_updated_at_ix ON src_app.orders (updated_at);

COMMENT ON TABLE src_app.customers IS 'Source system: customers';
COMMENT ON TABLE src_app.orders    IS 'Source system: orders. updated_at drives incremental extraction';

-- Least privilege: the ODS can read the source, nothing more
GRANT SELECT ON src_app.customers TO ods_app;
GRANT SELECT ON src_app.orders    TO ods_app;
